/// One execution request crossing the Agent-to-Tools runtime boundary.
pub struct ToolExecutionContext {
    /// Trusted session identity. It is never read from model-supplied input.
    pub session_id: Option<String>,
    pub tool_name: String,
    pub input: Value,
    /// Cancellation authority for the owning run or detached ToolRun.
    pub cancel: CancellationToken,
    /// Stable step identity, separate from the provider's input payload.
    pub step_id: Option<String>,
    /// Proof issued by the Tools authorization owner for this exact child
    /// operation. Test-only execution adapters may omit it.
    pub authorization_proof: Option<haven_tools::AuthorizationExecutionProof>,
}

/// Accept a review side-channel only when it names the exact canonical child
/// step generated by the Agent bridge for this execution.
pub(crate) fn sandbox_output_review_matches_step(result: &ToolResult, step_id: &str) -> bool {
    haven_common::types::is_canonical_id(step_id, "step")
        && result
            .signals
            .sandbox_output_review_step_ids
            .iter()
            .any(|review_step_id| review_step_id == step_id)
}

/// Executes a request carrying the authorization owner's proof and resolves
/// the tool's registrations. Tools revalidates that proof before each attempt.
#[async_trait]
pub trait ToolExecutionPort: Send + Sync {
    async fn execute(&self, context: ToolExecutionContext) -> anyhow::Result<ToolResult>;

    /// Start a child tool invocation through the durable background ToolRun
    /// owner. The context must carry the proof for the child tool itself.
    async fn start_background_tool(
        &self,
        _context: ToolExecutionContext,
    ) -> anyhow::Result<ToolResult> {
        anyhow::bail!("background ToolRun execution is unavailable on this execution port")
    }

    /// Execute Haven's synthetic CodeMode model tool with the Agent-owned
    /// authority for its independently checked child calls.
    async fn execute_codemode(
        &self,
        _context: ToolExecutionContext,
        _subcalls: Arc<dyn haven_tools::CodeModeSubcallPort>,
    ) -> anyhow::Result<ToolResult> {
        anyhow::bail!("CodeMode execution is unavailable on this execution port")
    }

    /// Execute one child through the CodeMode-only MCP exposure boundary.
    async fn execute_codemode_subcall(
        &self,
        _context: ToolExecutionContext,
    ) -> anyhow::Result<ToolResult> {
        anyhow::bail!("CodeMode child execution is unavailable on this execution port")
    }

    async fn registrations(
        &self,
        session_id: &str,
        tool_name: &str,
        output: &Value,
    ) -> Vec<ToolRegistration>;
}

/// The session runtime's complete authorization boundary.
///
/// Request preparation, decisions, receipts and grants cross this port as
/// typed values. The concrete policy engine remains owned by Tools.
#[async_trait]
pub trait ToolAuthorizationPort: Send + Sync {
    async fn risk_level(
        &self,
        session_id: Option<&str>,
        tool_name: &str,
        input: &Value,
    ) -> Result<RiskLevel, String>;

    async fn authorization_request(
        &self,
        session_id: Option<&str>,
        tool_name: &str,
        input: &Value,
    ) -> Result<AuthorizationRequest, String>;

    /// Resolve a child only through the current CodeMode exposure policy.
    /// Non-MCP test capabilities can keep the default authorization path.
    async fn authorization_request_for_codemode_subcall(
        &self,
        session_id: Option<&str>,
        tool_name: &str,
        input: &Value,
    ) -> Result<AuthorizationRequest, String> {
        self.authorization_request(session_id, tool_name, input)
            .await
    }

    async fn authorization_request_from_catalog(
        &self,
        catalog: &haven_tools::ToolCatalogSnapshot,
        session_id: Option<&str>,
        tool_name: &str,
        input: &Value,
    ) -> Result<AuthorizationRequest, String>;

    async fn authorize(&self, request: &AuthorizationRequest) -> AuthorizationDecision;

    async fn authorize_for_execution(
        &self,
        request: &AuthorizationRequest,
    ) -> haven_tools::AuthorizationCheck;

    async fn verify_receipt(
        &self,
        request: &AuthorizationRequest,
        receipt: &ConfirmationReceipt,
    ) -> Result<(), String>;

    async fn confirm_for_execution(
        &self,
        request: &AuthorizationRequest,
        receipt: &ConfirmationReceipt,
    ) -> Result<haven_tools::AuthorizationExecutionProof, String>;

    async fn verify_execution_proof(
        &self,
        request: &AuthorizationRequest,
        proof: &haven_tools::AuthorizationExecutionProof,
    ) -> Result<(), String>;

    async fn grant(
        &self,
        session_id: Option<&str>,
        capability: CapabilityScope,
        effect: PermissionEffect,
        scope: PermissionScope,
    );

    async fn apply_security(&self, security: &SecurityConfig);

    async fn set_permission_mode(&self, mode: PermissionMode);

    async fn set_boundaries(
        &self,
        sandbox_mode: SandboxMode,
        writable_roots: Vec<std::path::PathBuf>,
        network_policy: NetworkPolicy,
    );

    async fn list_permanent(&self) -> Vec<StoredPermission>;

    async fn revoke_permanent(&self, capability: &str) -> bool;

    async fn revoke_session_grant(&self, session_id: &str, capability: &CapabilityScope) -> bool;

    async fn clear_permanent(&self) -> usize;

    async fn clear_session_trust(&self, session_id: &str);

    async fn clear_all_trust(&self);

    async fn prompt_summary(&self) -> String;
}

/// Agent's use-case boundary for detached background ToolRuns.
#[async_trait]
pub trait AgentToolRunPort: Send + Sync {
    async fn attach_session(&self, tool_run_id: &str, session_id: &str);

    async fn cancel_owned_background_by_session_checked(
        &self,
        session_id: &str,
    ) -> anyhow::Result<()>;

    async fn cancel_owned_background_by_session(&self, session_id: &str);

    async fn list_for_session_views(&self, session_id: &str) -> Vec<ToolRunListView>;

    async fn restore(&self) -> ToolRunRestoreSummary;

    async fn acknowledge_completion(&self, tool_run_result_id: &str);

    async fn acknowledge_unowned_completion(&self, tool_run_result_id: &str);

    fn take_completion_receiver(&self) -> Option<Box<dyn ToolRunCompletionReceiverPort>>;
}

/// Agent's use-case boundary for Schedule trigger execution and occurrence
/// claims. Schedule plans and occurrence persistence remain owned by Tools.
#[async_trait]
pub trait AgentSchedulePort: Send + Sync {
    async fn restore(&self) -> anyhow::Result<ScheduleRestoreSummary>;

    async fn cancel_owned_by_session_checked(&self, session_id: &str) -> anyhow::Result<()>;

    async fn claim_execution(&self, schedule_run_id: &str, claim_id: &str) -> anyhow::Result<bool>;

    async fn release_execution(
        &self,
        schedule_run_id: &str,
        claim_id: &str,
    ) -> anyhow::Result<bool>;

    async fn finish(
        &self,
        schedule_run_id: &str,
        status: haven_common::lifecycle::ScheduleRunStatus,
        result_summary: Option<&str>,
        error_reason: Option<&str>,
    ) -> anyhow::Result<bool>;

    fn take_fired_receiver(&self) -> Option<Box<dyn ScheduleFiredReceiverPort>>;

    async fn shutdown(&self);
}

#[async_trait]
pub trait ScheduleFiredReceiverPort: Send {
    async fn recv(&mut self) -> Option<haven_tools::ScheduleRunTriggered>;
}

/// Recovered completion stream. Recovery and outbox access stay inside Tools.
#[async_trait]
pub trait ToolRunCompletionReceiverPort: Send {
    async fn recv_result_with_recovery(&mut self) -> Option<ToolRunCompletion>;
}

